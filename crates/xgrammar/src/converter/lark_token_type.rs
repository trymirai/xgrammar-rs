//! Token kinds produced by the Lark lexer.

/// The kind of a Lark token.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LarkTokenType {
    Name,
    String,
    Regex,
    Number,
    SpecialToken,
    GrammarRef,
    Json,
    RegexExt,
    GrammarOptions,
    Import,
    Ignore,
    Lark,
    If,
    UnsupportedDirective,
    Colon,
    DoubleColon,
    Comma,
    Dot,
    DotDot,
    Arrow,
    Equals,
    LParen,
    RParen,
    LBracket,
    RBracket,
    LBrace,
    RBrace,
    Pipe,
    And,
    Tilde,
    Question,
    Star,
    Plus,
    Newline,
    End,
}
